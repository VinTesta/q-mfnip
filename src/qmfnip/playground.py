import hashlib
import json
import time
from dataclasses import dataclass, field
from datetime import datetime
from pathlib import Path

from .evaluation import evaluate_run
from .instances import Instance, Scenario, max_flow
from .outputs import DEFAULT_OUTPUT_ROOT, ExperimentOutput, capture_environment, to_jsonable
from .solvers import MILPSolver, Solver, SolveResult

RECORD_KEYS = (
    "backend",
    "logical_qubits",
    "physical_qubits",
    "two_qubit_gates",
    "circuit_depth",
    "search_space_size",
    "optimal_count",
    "oracle_queries",
    "classical_evaluations",
    "queries_to_optimum",
    "evaluations_to_optimum",
    "found_optimum",
    "rounds",
    "query_budget",
    "within_query_budget",
    "enumeration_time_s",
)
RECORDS_FILE = "runs/records.jsonl"
REFERENCES_FILE = "references.jsonl"


@dataclass
class ExperimentConfig:
    scenario: Scenario
    solvers: list[Solver]
    repetitions: int = 1
    time_limit: float = 60.0
    base_seed: int = 0
    reference: Solver | None = field(default_factory=MILPSolver)
    reference_time_limit: float = 600.0
    allow_hardware: bool = False
    output_root: Path = DEFAULT_OUTPUT_ROOT

    def to_dict(self) -> dict:
        return {
            "scenario": self.scenario.to_dict(),
            "solvers": [solver.describe() for solver in self.solvers],
            "repetitions": self.repetitions,
            "time_limit_s": self.time_limit,
            "base_seed": self.base_seed,
            "reference": None if self.reference is None else self.reference.describe(),
            "reference_time_limit_s": self.reference_time_limit,
            "allow_hardware": self.allow_hardware,
        }


def _derive_seed(*parts) -> int:
    return int(hashlib.sha256("|".join(map(str, parts)).encode()).hexdigest()[:8], 16)


def _timed_solve(solver: Solver, instance: Instance, seed: int, time_limit: float) -> tuple[SolveResult, float]:
    start = time.perf_counter()
    try:
        result = solver.solve(instance, seed, time_limit)
    except Exception as error:
        result = SolveResult(None, "error", metadata={"error": f"{type(error).__name__}: {error}"})
    return result, time.perf_counter() - start


def _now() -> str:
    return datetime.now().astimezone().isoformat(timespec="seconds")


def run_experiment(
    config: ExperimentConfig, resume: Path | str | None = None, verbose: bool = True
) -> ExperimentOutput:
    labels = [solver.label for solver in config.solvers]
    if len(set(labels)) != len(labels):
        raise ValueError(f"Solver labels must be unique, got {labels}; pass label=... to distinguish them")
    candidates = config.solvers + ([config.reference] if config.reference is not None else [])
    hardware = [solver.label for solver in candidates if solver.requires_hardware()]
    if hardware and not config.allow_hardware:
        raise PermissionError(
            f"Solvers {hardware} run on quantum hardware; validate them on a simulator and set allow_hardware=True"
        )

    instances = list(config.scenario.instances())
    if resume is None:
        output = ExperimentOutput.create(
            labels, config.scenario.family, [instance.n for instance in instances], config.repetitions,
            config.output_root,
        )
        output.update_manifest(
            {
                "status": "running",
                "started_at": _now(),
                "config": config.to_dict(),
                "instances": {instance.instance_id: instance.content_hash for instance in instances},
            }
        )
        output.write_json("environment.json", capture_environment())
        for instance in instances:
            output.write_instance(instance)
    else:
        output = ExperimentOutput(resume)
        manifest = output.read_json("manifest.json")
        expected = {instance.instance_id: instance.content_hash for instance in instances}
        if manifest is None or manifest.get("instances") != expected:
            raise ValueError(f"Instances generated by this config do not match the experiment in {output.path}")
        resumed_at = _now()
        output.update_manifest(
            {"status": "running", "resumed_at": [*manifest.get("resumed_at", []), resumed_at]}
        )
        output.write_json(f"environment_resumed_{resumed_at.replace(':', '-')}.json", capture_environment())

    references = {record["instance_id"]: record for record in output.read_records(REFERENCES_FILE)}
    done = {
        (record["instance_id"], record["solver"], record["repetition"])
        for record in output.read_records(RECORDS_FILE)
    }
    total = len(instances) * len(config.solvers) * config.repetitions
    completed = len(done)

    for instance in instances:
        if config.reference is not None and instance.instance_id not in references:
            reference_seed = _derive_seed(config.base_seed, instance.content_hash, "reference")
            reference_result, reference_time = _timed_solve(
                config.reference, instance, reference_seed, config.reference_time_limit
            )
            delivered = reference_result.interdicted is not None
            within_budget = delivered and instance.cost[reference_result.interdicted].sum() <= instance.budget
            reference = {
                "instance_id": instance.instance_id,
                "instance_hash": instance.content_hash,
                "solver": config.reference.label,
                "status": reference_result.status,
                "certified": bool(reference_result.certified_optimal and within_budget),
                "optimal_flow": max_flow(instance, reference_result.interdicted) if delivered else None,
                "wall_time_s": reference_time,
                "time_limit_s": config.reference_time_limit,
            }
            output.append_record(REFERENCES_FILE, reference)
            references[instance.instance_id] = reference

        for solver in config.solvers:
            for repetition in range(config.repetitions):
                if (instance.instance_id, solver.label, repetition) in done:
                    continue
                run_seed = _derive_seed(config.base_seed, instance.content_hash, solver.label, repetition)
                result, wall_time = _timed_solve(solver, instance, run_seed, config.time_limit)
                evaluation = evaluate_run(
                    instance, result, wall_time, config.time_limit, references.get(instance.instance_id)
                )
                extra_metadata = {key: value for key, value in result.metadata.items() if key not in RECORD_KEYS}
                record = {
                    "experiment_id": output.experiment_id,
                    "instance_id": instance.instance_id,
                    "instance_hash": instance.content_hash,
                    "family": instance.family,
                    "n_nodes": instance.n,
                    "n_arcs": instance.m,
                    "budget_fraction": instance.budget_fraction,
                    "budget": instance.budget,
                    "instance_seed": instance.seed,
                    "solver": solver.label,
                    "solver_class": solver.short_name,
                    "solver_params": json.dumps(to_jsonable(solver.params), sort_keys=True),
                    "repetition": repetition,
                    "run_seed": run_seed,
                    "status": result.status,
                    "certified_optimal": result.certified_optimal,
                    "timestamp": _now(),
                    "time_limit_s": config.time_limit,
                    "wall_time_s": wall_time,
                    "solver_time_s": result.solver_time,
                    "qpu_time_s": result.qpu_time,
                    "queue_time_s": result.queue_time,
                    "compile_time_s": result.compile_time,
                    "objective_reported": result.objective,
                    **evaluation,
                    **{key: result.metadata.get(key) for key in RECORD_KEYS},
                    "metadata": json.dumps(to_jsonable(extra_metadata), sort_keys=True),
                }
                output.append_record(RECORDS_FILE, record)
                completed += 1
                if verbose:
                    gap = "-" if evaluation["gap"] is None else f"{evaluation['gap']:.4f}"
                    print(
                        f"[{completed}/{total}] {solver.label:>16} {instance.instance_id:<36} rep={repetition} "
                        f"status={result.status:<10} wall={wall_time:8.3f}s gap={gap}",
                        flush=True,
                    )

    output.write_runs(output.load_runs(from_records=True))
    output.update_manifest({"status": "completed", "finished_at": _now()})
    return output
